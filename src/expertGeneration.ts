let experts: Array<{ id: ExpertId; name: string }> = [];
let studentExpertIdSet = new Set<ExpertId>(["brainstorm", "positioning", "business", "pitch", "script", "media"]);

function configureExpertGeneration(expertRecords: Array<{ id: ExpertId; name: string }>, studentExpertIds: ExpertId[]) {
  experts = expertRecords;
  studentExpertIdSet = new Set(studentExpertIds);
}

function isStudentExpertId(expertId: ExpertId) {
  return studentExpertIdSet.has(expertId);
}

function nowTime() {
  return new Date().toLocaleTimeString("zh-CN", { hour: "2-digit", minute: "2-digit" });
}

function makeId(prefix: string) {
  return `${prefix}-${Math.floor(10000 + Math.random() * 90000)}`;
}

function makePersistentId(prefix: string) {
  return `${prefix}-${window.crypto?.randomUUID?.() || `${Date.now()}-${Math.floor(Math.random() * 1_000_000)}`}`;
}

function getArtifactType(expertId: ExpertId): ArtifactType {
  if (expertId === "brainstorm") return "BRAINSTORM";
  if (expertId === "positioning") return "POSITIONING";
  if (expertId === "market") return "MARKET";
  if (expertId === "business") return "BP";
  if (expertId === "pitch") return "PPT";
  if (expertId === "script") return "SCRIPT";
  if (expertId === "defense") return "DEFENSE";
  return "MEDIA";
}

function isArtifactType(value: unknown): value is ArtifactType {
  return typeof value === "string" && value in artifactLabels;
}

